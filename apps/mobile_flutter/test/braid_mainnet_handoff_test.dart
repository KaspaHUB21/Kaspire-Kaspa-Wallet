import 'package:kasvault_wallet/src/services/network_settings.dart';

class MemoryStore implements EncryptedStore {
  final values = <String, String>{};
  @override
  Future<String?> read(String k) async => values[k];
  @override
  Future<void> write(String k, String v) async => values[k] = v;
  @override
  Future<void> delete(String k) async => values.remove(k);
}

class SnapshotClock extends BraidClock {
  SnapshotClock(this.daa) : super(http.Client(), mainnet: true);
  final int daa;
  @override
  Future<List<int>> read() async => [daa, daa];
}

void main() {
  test(
      'captured unsigned Mainnet API build passes actual Dart-to-Rust boundary',
      () async {
    NetworkSettings.network.value = KaspaNetwork.mainnet;
    final b = jsonDecode(
            File('/workspace/braid-mainnet-build.json').readAsStringSync())
        as Map<String, dynamic>;
    final funding =
        File('/workspace/braid-mainnet-funding.json').readAsStringSync();
    final address = '${b['pskt']['inputs'][0]['utxo']['address']}';
    final originalIntent = '${b['terms']['intent']}';
    final service = BraidService(
        store: MemoryStore(),
        clock: SnapshotClock(int.parse('${b['daaNow']}')),
        client: MockClient((r) async {
          if (r.method == 'POST') {
            expect(r.url.path, '/api/mainnet/router/deposit-build');
            final body = jsonDecode(r.body) as Map;
            expect(body['walletFeeBps'], 100);
            // Rebind only the fixture's nonce commitment to the fresh random
            // nonce generated by production code. Never submit this fixture.
            final intent = BraidService.digest([
              ...BraidService.bytes('${body['nonce']}'),
              ...utf8.encode('${b['ref']}')
            ]);
            b['terms']['intent'] = intent;
            final redeem =
                '${b['coin']['redeem']}'.replaceAll(originalIntent, intent);
            b['pskt']['outputs'][b['coinIdx']]['scriptPublicKey'] =
                BraidService.scriptHash(redeem);
            final payload = '${b['pskt']['payload']}';
            final data = payload
                .substring(0, payload.length - 8)
                .replaceAll(originalIntent, intent);
            b['pskt']['payload'] = data +
                BraidService.digest(BraidService.bytes(data)).substring(0, 8);
            return http.Response.bytes(utf8.encode(jsonEncode(b)), 200,
                headers: {'content-type': 'application/json; charset=utf-8'});
          }
          expect(r.url.path, '/dex-test-v1/kasseal-mainnet/utxos');
          return http.Response(funding, 200);
        }));
    final q = <String, dynamic>{
      ...b['quote'] as Map<String, dynamic>,
      'localAt': DateTime.now().millisecondsSinceEpoch,
      'localFromId': BraidService.zero,
      'localToId': BraidService.mainnetTokens[1].id,
      'localAmount': '3000000000',
      'localFloor': b['terms']['minOut'],
      'localSlippage': 100
    };
    final receipt = await service.build(address, q);
    final request = receipt['request'] as Map;
    expect(request['profile'], 'braid-mainnet-deposit-v1');
    Future<ProcessResult> inspect(Map request) async {
      final process =
          await Process.start('../../target/debug/braid_inspect', []);
      process.stdin.write(jsonEncode(request));
      await process.stdin.close();
      final out = utf8.decoder.bind(process.stdout).join();
      final err = utf8.decoder.bind(process.stderr).join();
      return ProcessResult(
          process.pid, await process.exitCode, await out, await err);
    }

    final good = await inspect(request);
    expect(good.exitCode, 0, reason: '${good.stderr}');
    expect((jsonDecode('${good.stdout}') as Map)['finalFeeKnown'], true);
    (request['tradeSummary'] as Map)['terms']['wfeePk'] = '0' * 64;
    expect((await inspect(request)).exitCode, isNot(0));
  }, skip: !File('/workspace/braid-mainnet-build.json').existsSync());
}
