use silverscript_v1::{
    ast::Expr,
    compiler::{compile_contract, CompileOptions},
};
use std::{env, fs, path::PathBuf};

// Build-time compiler output, not a second handwritten contract. All substituted
// values remain canonically encoded script pushes. Regenerated from pinned
// official SilverScript; native parity tests verify bytecode, tags and hash.
fn main() {
    println!("cargo:rerun-if-changed=src/vault_time_lock.sil");
    println!("cargo:rerun-if-changed=src/vault_dead_man_switch.sil");
    let mut generated =
        String::from("// Generated by the pinned official SilverScript compiler.\n");
    for (kind, file) in [
        ("timeLock", "vault_time_lock.sil"),
        ("deadManSwitch", "vault_dead_man_switch.sil"),
    ] {
        let source = fs::read_to_string(format!("src/{file}")).unwrap();
        let owner = vec![0x35; 32];
        let beneficiary = vec![0x46; 32];
        let instance = vec![0x57; 32];
        let limit: i64 = 0x12345678;
        let mut args = vec![Expr::bytes(owner.clone())];
        if kind == "deadManSwitch" {
            args.push(Expr::bytes(beneficiary.clone()));
        }
        args.push(Expr::int(limit));
        args.push(Expr::bytes(instance.clone()));
        let compiled = compile_contract(&source, &args, CompileOptions::default()).unwrap();
        let bytes = &compiled.bytecode;
        let limit_bytes = vec![0x78, 0x56, 0x34, 0x12];
        let markers = [
            ("owner", owner),
            ("beneficiary", beneficiary),
            ("limit", limit_bytes),
            ("instance", instance),
        ];
        let mut regions = vec![];
        // Walk actual opcodes. Never replace a byte pattern inside another push.
        let mut i = 0;
        while i < bytes.len() {
            let start = i;
            let op = bytes[i];
            i += 1;
            let length = match op {
                1..=75 => op as usize,
                76 => {
                    let n = bytes[i] as usize;
                    i += 1;
                    n
                }
                77 => {
                    let n = u16::from_le_bytes([bytes[i], bytes[i + 1]]) as usize;
                    i += 2;
                    n
                }
                78 => {
                    let n = u32::from_le_bytes(bytes[i..i + 4].try_into().unwrap()) as usize;
                    i += 4;
                    n
                }
                _ => 0,
            };
            assert!(i + length <= bytes.len());
            if length > 0 {
                for (name, value) in &markers {
                    if &bytes[i..i + length] == value.as_slice() {
                        regions.push((start, i + length, *name));
                    }
                }
            }
            i += length;
        }
        for name in ["owner", "limit", "instance"] {
            assert!(regions.iter().any(|r| r.2 == name), "missing {kind} {name}");
        }
        if kind == "deadManSwitch" {
            assert!(regions.iter().any(|r| r.2 == "beneficiary"));
        }
        let state_start = compiled.state_layout.start;
        let state_end = state_start + compiled.state_layout.len;
        generated.push_str(&format!("#[allow(unused_variables, unused_assignments)]\nfn materialize_{}(owner: &[u8], beneficiary: &[u8], limit: i64, instance: &[u8]) -> Result<PortableCompiled> {{\n let mut out = Vec::<u8>::new(); let mut state_start = None; let mut state_end = None;\n", if kind == "timeLock" { "time_lock" } else { "dead_man_switch" }));
        let mark = |position, output: &mut String| {
            if position == state_start {
                output.push_str("state_start = Some(out.len());\n");
            }
            if position == state_end {
                output.push_str("state_end = Some(out.len());\n");
            }
        };
        let chunk = |start: usize, end: usize, output: &mut String| {
            let mut cursor = start;
            let mut boundaries = vec![end];
            for n in [state_start, state_end] {
                if n > start && n < end {
                    boundaries.push(n);
                }
            }
            boundaries.sort_unstable();
            boundaries.dedup();
            for n in boundaries {
                mark(cursor, output);
                if cursor < n {
                    output.push_str(&format!(
                        "out.extend_from_slice(&{:?});\n",
                        &bytes[cursor..n]
                    ));
                }
                cursor = n;
            }
        };
        let mut cursor = 0;
        for (start, end, name) in regions {
            assert!(!(start < state_start && state_start < end));
            assert!(!(start < state_end && state_end < end));
            chunk(cursor, start, &mut generated);
            mark(start, &mut generated);
            if name == "limit" {
                generated.push_str("out.extend(ScriptBuilder::new().add_i64(limit).map_err(|e| CoreError::Transaction(e.to_string()))?.drain());\n");
            } else {
                generated.push_str(&format!("out.extend(ScriptBuilder::new().add_data({name}).map_err(|e| CoreError::Transaction(e.to_string()))?.drain());\n"));
            }
            cursor = end;
        }
        chunk(cursor, bytes.len(), &mut generated);
        mark(bytes.len(), &mut generated);
        generated.push_str("let mut tags = std::collections::BTreeMap::new();\n");
        for (name, tag) in compiled.dispatch_tags {
            generated.push_str(&format!("tags.insert({name:?}.to_owned(), {tag:?});\n"));
        }
        generated.push_str("Ok(PortableCompiled {bytecode: out, dispatch_tags: tags, state_start: state_start.unwrap(), state_end: state_end.unwrap()})\n}\n");
    }
    fs::write(
        PathBuf::from(env::var_os("OUT_DIR").unwrap()).join("vault_templates.rs"),
        generated,
    )
    .unwrap();
}
